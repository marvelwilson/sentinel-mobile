CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'customer',
  created_at TEXT NOT NULL,
  auth_version INTEGER NOT NULL DEFAULT 0,
  email_verified INTEGER NOT NULL DEFAULT 1
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_unique ON users (lower(email));

CREATE TABLE IF NOT EXISTS cars (
  id TEXT PRIMARY KEY,
  make TEXT NOT NULL,
  model TEXT NOT NULL,
  year INTEGER NOT NULL,
  price_usd DOUBLE PRECISION NOT NULL,
  mileage INTEGER NOT NULL DEFAULT 0,
  transmission TEXT NOT NULL DEFAULT 'Automatic',
  body_type TEXT NOT NULL DEFAULT 'Sedan',
  description TEXT NOT NULL DEFAULT '',
  image_url TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'available',
  reserved_order TEXT,
  reserved_until TEXT,
  created_at TEXT NOT NULL,
  available_stock INTEGER NOT NULL DEFAULT 1 CHECK (available_stock >= 0)
);

CREATE TABLE IF NOT EXISTS orders (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id),
  status TEXT NOT NULL,
  payment_method TEXT NOT NULL,
  currency TEXT NOT NULL,
  subtotal_usd DOUBLE PRECISION NOT NULL,
  discount_usd DOUBLE PRECISION NOT NULL DEFAULT 0,
  total_usd DOUBLE PRECISION NOT NULL,
  promo_code TEXT,
  buyer_details TEXT NOT NULL,
  payment_details TEXT NOT NULL DEFAULT '{}',
  created_at TEXT NOT NULL,
  expires_at TEXT
);

CREATE TABLE IF NOT EXISTS order_items (
  order_id TEXT NOT NULL REFERENCES orders(id),
  car_id TEXT NOT NULL REFERENCES cars(id),
  make TEXT NOT NULL,
  model TEXT NOT NULL,
  year INTEGER NOT NULL,
  price_usd DOUBLE PRECISION NOT NULL,
  quantity INTEGER NOT NULL DEFAULT 1,
  PRIMARY KEY (order_id, car_id)
);

CREATE TABLE IF NOT EXISTS promos (
  id TEXT PRIMARY KEY,
  code TEXT NOT NULL,
  kind TEXT NOT NULL,
  amount DOUBLE PRECISION NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  uses_limit INTEGER,
  uses_count INTEGER NOT NULL DEFAULT 0 CHECK (uses_count >= 0),
  expires_at TEXT,
  created_at TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  pinned INTEGER NOT NULL DEFAULT 0,
  brands TEXT NOT NULL DEFAULT '[]'
);
CREATE UNIQUE INDEX IF NOT EXISTS promos_code_unique ON promos (lower(code));
CREATE UNIQUE INDEX IF NOT EXISTS promos_single_pinned ON promos (pinned) WHERE pinned = 1;

CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
  sid TEXT PRIMARY KEY,
  sess TEXT NOT NULL,
  expires BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS contact_messages (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT NOT NULL,
  subject TEXT NOT NULL,
  message TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'new',
  created_at TEXT NOT NULL,
  confirmation_status TEXT
);
CREATE TABLE IF NOT EXISTS call_requests (
  id TEXT PRIMARY KEY,
  token_hash TEXT NOT NULL,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT NOT NULL,
  preferred_at TEXT NOT NULL,
  timezone TEXT NOT NULL,
  notes TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'requested',
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS call_requests_preferred_at ON call_requests (preferred_at, status);
CREATE UNIQUE INDEX IF NOT EXISTS call_requests_active_slot ON call_requests (preferred_at)
  WHERE status IN ('requested', 'confirmed');
CREATE TABLE IF NOT EXISTS bank_accounts (
  id TEXT PRIMARY KEY,
  bank_name TEXT NOT NULL,
  account_name TEXT NOT NULL,
  account_number TEXT NOT NULL,
  routing_number TEXT NOT NULL DEFAULT '',
  swift_code TEXT NOT NULL DEFAULT '',
  instructions TEXT NOT NULL DEFAULT '',
  currency TEXT,
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS bank_notifications (
  order_id TEXT PRIMARY KEY REFERENCES orders(id),
  status TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS payment_proofs (
  order_id TEXT PRIMARY KEY REFERENCES orders(id),
  available_at TEXT NOT NULL,
  content_type TEXT,
  contents BYTEA,
  uploaded_at TEXT
);
CREATE TABLE IF NOT EXISTS order_tracking (
  order_id TEXT PRIMARY KEY REFERENCES orders(id),
  code TEXT NOT NULL UNIQUE,
  shipment_status TEXT
);
CREATE TABLE IF NOT EXISTS shipment_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id TEXT NOT NULL REFERENCES orders(id),
  status TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS tracking_emails (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id TEXT NOT NULL REFERENCES orders(id),
  kind TEXT NOT NULL,
  shipment_status TEXT,
  event_at TEXT,
  status TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS account_codes (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id),
  purpose TEXT NOT NULL,
  stage TEXT NOT NULL,
  target_email TEXT,
  code_hash TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0,
  UNIQUE (user_id, purpose)
);
CREATE TABLE IF NOT EXISTS code_requests (
  user_id TEXT NOT NULL REFERENCES users(id),
  purpose TEXT NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS order_promos (
  order_id TEXT NOT NULL REFERENCES orders(id),
  position INTEGER NOT NULL,
  code TEXT NOT NULL,
  discount_usd DOUBLE PRECISION NOT NULL,
  PRIMARY KEY (order_id, position)
);

